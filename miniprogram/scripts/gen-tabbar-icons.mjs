// 生成 custom-tab-bar 的 PNG 图标（base64 内嵌，解决微信组件 wxss @font-face 不生效问题）。
// 从 bootstrap-icons 的 SVG 渲染 81×81 PNG（两态：未激活灰 / 激活白）。
// 用法：node scripts/gen-tabbar-icons.mjs
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Resvg } from '@resvg/resvg-js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const iconsDir = join(root, 'node_modules/bootstrap-icons/icons')

const TABS = [
  { key: 'grid', name: 'grid.svg' },
  { key: 'calendar3', name: 'calendar3.svg' },
  { key: 'chat-dots', name: 'chat-dots.svg' },
  { key: 'gear', name: 'gear.svg' }
]
const NORMAL = '#9aa3bd'
const ACTIVE = '#ffffff'
const SIZE = 81

const out = {}
for (const tab of TABS) {
  const svgPath = join(iconsDir, tab.name)
  if (!existsSync(svgPath)) {
    console.warn(`⚠ 跳过缺失 SVG: ${tab.name}`)
    continue
  }
  let svg = readFileSync(svgPath, 'utf8')
  const render = (color) => {
    const colored = svg.replace(/fill="currentColor"/g, `fill="${color}"`)
    const resvg = new Resvg(colored, { fitTo: { mode: 'width', value: SIZE } })
    return resvg.render().asPng()
  }
  out[tab.key] = {
    normal: `data:image/png;base64,${render(NORMAL).toString('base64')}`,
    active: `data:image/png;base64,${render(ACTIVE).toString('base64')}`
  }
}

const dest = join(root, 'src', 'custom-tab-bar', 'icons.gen.js')
mkdirSync(dirname(dest), { recursive: true })
const ts = `// AUTO-GENERATED by scripts/gen-tabbar-icons.mjs — 请勿手动编辑
// 重新生成：node scripts/gen-tabbar-icons.mjs
module.exports = ${JSON.stringify(out, null, 2)}
`
writeFileSync(dest, ts, 'utf8')
console.log(`✓ 已生成 ${dest}（${Object.keys(out).length} 个 tab 图标 × 2 态）`)
